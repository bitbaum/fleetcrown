/**
 * Substitute {{NAME}} / {{DESCRIPTION}} placeholders in a file body.
 * Kept tiny — no real templating engine. If we add more placeholders or
 * conditional blocks, lift to a proper templating step.
 */
export function renderTemplate(
  content: string,
  values: { name: string; description: string },
): string {
  return content
    .replaceAll("{{NAME}}", values.name)
    .replaceAll("{{DESCRIPTION}}", values.description);
}
