// Project starter templates seeded by /api/projects/create-with-github when
// the user picks one. Each template is a small set of files that get committed
// to the brand-new repo in one Git Tree API call (single round-trip).
//
// Why inline files rather than a GitHub template-repo?
//   1. No external repo to maintain. Add a starter by editing this file.
//   2. Templates can include the user's chosen project name via {{NAME}}
//      placeholders — we substitute server-side before commit.
//   3. Single API call vs. forking + maintaining a template-repo on GitHub.
//
// Adding a starter: append a new TEMPLATES entry with its file map. Keep each
// starter small (< 15 files) so the commit stays under GitHub's tree-size
// limits and the choice list stays scannable.

export type TemplateId = "bare" | "nextjs-tailwind";

export interface TemplateMeta {
  id: TemplateId;
  label: string;
  description: string;
  /** Map of repo-relative path → file contents. {{NAME}} is replaced with
   *  the slugged repo name; {{DESCRIPTION}} with the project description. */
  files: Record<string, string>;
}

